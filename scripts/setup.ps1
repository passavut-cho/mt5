#Requires -Version 5.1
<#
.SYNOPSIS
  One-time setup: detect the MT5 terminal, write scripts/config.local.ps1,
  and create directory junctions from the terminal's MQL5 folder into this repo.
  Junctions do NOT need Administrator rights.
.EXAMPLE
  powershell -NoProfile -ExecutionPolicy Bypass -File scripts/setup.ps1
  powershell -NoProfile -ExecutionPolicy Bypass -File scripts/setup.ps1 -TerminalId D0E8209F77C8CF37AD8BF550E51FF075
#>
param([string]$TerminalId)
$ErrorActionPreference = 'Stop'
$repo = (Resolve-Path "$PSScriptRoot\..").Path
$base = Join-Path $env:APPDATA 'MetaQuotes\Terminal'
if (-not (Test-Path $base)) { throw "MT5 data folder not found: $base  (start MT5 once first)" }

$cands = @(Get-ChildItem $base -Directory | ForEach-Object {
    $o = Join-Path $_.FullName 'origin.txt'
    if (Test-Path $o) {
        $install = (Get-Content $o -Raw).Trim()
        if (Test-Path (Join-Path $install 'terminal64.exe')) {
            [pscustomobject]@{ Id = $_.Name; DataDir = $_.FullName; InstallDir = $install }
        }
    }
})
if ($cands.Count -eq 0) { throw "No MT5 terminal found under $base (portable installs are not supported by this script)" }

if ($TerminalId) {
    $t = $cands | Where-Object Id -eq $TerminalId
    if (-not $t) { throw "TerminalId $TerminalId not found" }
} elseif ($cands.Count -eq 1) {
    $t = $cands[0]
} else {
    for ($i = 0; $i -lt $cands.Count; $i++) { Write-Host "[$i] $($cands[$i].InstallDir)  ($($cands[$i].Id))" }
    $t = $cands[[int](Read-Host 'Select terminal index')]
}
Write-Host "Using terminal: $($t.InstallDir)" -ForegroundColor Cyan

# --- config.local.ps1 (gitignored) ---
@"
# Generated by setup.ps1 on $(Get-Date -Format s) - machine specific, do not commit
`$MT5_DATA_DIR   = '$($t.DataDir)'
`$MT5_TERMINAL   = '$(Join-Path $t.InstallDir 'terminal64.exe')'
`$MT5_METAEDITOR = '$(Join-Path $t.InstallDir 'metaeditor64.exe')'
"@ | Set-Content (Join-Path $PSScriptRoot 'config.local.ps1') -Encoding UTF8

# --- junctions ---
$mql5 = Join-Path $t.DataDir 'MQL5'
New-Item -ItemType Directory -Force -Path "$mql5\Files" | Out-Null
$links = @(
    @{ Link = "$mql5\Experts\SmartEA"; Target = "$repo\src\Experts\SmartEA" },
    @{ Link = "$mql5\Include\SmartEA"; Target = "$repo\src\Include" },
    @{ Link = "$mql5\Scripts\SmartEA"; Target = "$repo\src\Scripts" },
    @{ Link = "$mql5\Files\SmartEA";   Target = "$repo\data\files" },
    @{ Link = "$mql5\Indicators\SmartEA"; Target = "$repo\src\Indicators" }
)
foreach ($l in $links) {
    if (Test-Path $l.Link) {
        $item = Get-Item $l.Link -Force
        if ($item.LinkType -eq 'Junction') {
            if ($item.Target -contains $l.Target) { Write-Host "OK (exists)  $($l.Link)"; continue }
            throw "$($l.Link) is a junction to another target: $($item.Target). Remove it with: cmd /c rmdir `"$($l.Link)`""
        }
        throw "$($l.Link) already exists as a real folder. Move it away first (it is NOT a junction)."
    }
    New-Item -ItemType Junction -Path $l.Link -Target $l.Target | Out-Null
    Write-Host "Created      $($l.Link) -> $($l.Target)" -ForegroundColor Green
}
New-Item -ItemType Directory -Force -Path (Join-Path $t.DataDir 'reports') | Out-Null
Write-Host "`nDone. Next: powershell -NoProfile -ExecutionPolicy Bypass -File scripts/compile.ps1" -ForegroundColor Cyan
